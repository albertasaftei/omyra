/** A repeating, chord-aware ostinato with a slow eight-phrase dynamic arc. */
export function cinematicStep(
  profile: Soundscape,
  step: number,
  density: number,
) {
  const pulse = profile.pulse!;
  const phraseSteps = pulse.pattern.length * pulse.bars;
  const chord =
    profile.chords[Math.floor(step / phraseSteps) % profile.chords.length];
  const index = step % pulse.pattern.length;
  const stride = density < 0.35 ? 4 : density < 0.7 ? 2 : 1;
  const swell = profile.drive
    ? 0.55 +
      0.45 *
        Math.sin((Math.PI * (step % (phraseSteps * 8))) / (phraseSteps * 8))
    : 1;
  return {
    swell,
    chord,
    interval: chord[pulse.pattern[index] % chord.length] + (pulse.octave ?? 12),
    voiced: !pulse.rests?.includes(index),
    active: density > 0 && step % stride === 0,
    velocity:
      swell *
      ((pulse.accents ?? [0]).includes(index) ? 0.5 : 0.32) *
      (0.8 +
        0.2 *
          Math.sin((Math.PI * (step % (phraseSteps * 8))) / (phraseSteps * 8))),
    phraseStart: step % phraseSteps === 0,
  };
}
